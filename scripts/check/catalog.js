import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument, stringify } from 'yaml';
import { issueForms } from './issue-forms.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const fields = ['id', 'title', 'category', 'url', 'status'];
const generated = '<!-- Generated by scripts/check/catalog.js; do not edit manually. -->\n';
const read = filename => fs.readFileSync(filename, 'utf8');
const slash = filename => filename.split(path.sep).join('/');
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;

export function markdownFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const filename = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`目录文件不能是符号链接: ${filename}`);
    return entry.isDirectory() ? markdownFiles(filename) : entry.name.endsWith('.md') ? [filename] : [];
  }).sort(compare);
}

export function loadResources(root = ROOT) {
  const categories = JSON.parse(read(path.join(root, 'resources/categories.json')));
  const codes = categories.map(c => c.id);
  if (new Set(codes).size !== codes.length) throw new Error('分类 ID 重复');
  const groups = new Map();
  for (const c of categories) {
    if (!/^[a-z0-9-]+\/[a-z0-9-]+$/.test(c.id)) throw new Error(`非法分类 ID: ${c.id}`);
    const group = c.id.split('/')[0];
    if (groups.has(group) && groups.get(group) !== c.group) throw new Error(`分类组名称不一致: ${group}`);
    groups.set(group, c.group);
  }
  const resources = [], ids = new Set(), urls = new Set(), badges = new Map();
  for (const filename of markdownFiles(path.join(root, 'resources'))) {
    const relative = slash(path.relative(path.join(root, 'resources'), filename));
    if (path.basename(filename) === 'readme.md' && relative.split('/').length <= 2) continue;
    const match = read(filename).match(/^---\n([\s\S]*?)\n---\n\n([\s\S]*)$/);
    if (!match) throw new Error(`缺少 YAML 元数据: ${filename}`);
    const document = parseDocument(match[1], { uniqueKeys: true });
    if (document.errors.length) {
      const error = document.errors[0];
      throw new Error(error.code === 'DUPLICATE_KEY' ? `重复元数据字段: ${filename}` : error.message);
    }
    const data = document.toJS();
    if (!data || Array.isArray(data) || Object.keys(data).sort().join() !== [...fields].sort().join()) {
      throw new Error(`元数据字段必须是 ${fields.join(', ')}: ${filename}`);
    }
    if (Object.values(data).some(v => typeof v !== 'string' || !v.trim() || /[\r\n]/.test(v))) {
      throw new Error(`元数据必须是非空单行字符串: ${filename}`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(data.id) || ids.has(data.id)) throw new Error(`非法或重复资源 ID: ${data.id}`);
    ids.add(data.id);
    if (!codes.includes(data.category)) throw new Error(`未知分类: ${data.category}`);
    if (slash(path.relative(root, filename)) !== `resources/${data.category}/${data.id}.md`) throw new Error(`文件路径与 ID/分类不一致: ${filename}`);
    if (!['unknown', 'active', 'archived'].includes(data.status)) throw new Error(`未知状态: ${data.status}`);
    let url;
    try { url = new URL(data.url); } catch { throw new Error(`资源主链接必须是 HTTP(S) URL: ${filename}`); }
    if (!['http:', 'https:'].includes(url.protocol) || !url.hostname || url.username || url.password) throw new Error(`资源主链接必须是 HTTP(S) URL: ${filename}`);
    const canonical = JSON.stringify([url.hostname.toLowerCase(), url.pathname.replace(/\/+$/, ''), url.search, url.hash]);
    if (urls.has(canonical)) throw new Error(`重复资源主链接: ${data.url}`);
    urls.add(canonical);
    const body = match[2];
    if (!body.startsWith(`# ${data.title}\n`) || !body.slice(body.indexOf('\n') + 1).trim()) throw new Error(`正文必须以匹配标题的 H1 开头并包含介绍/链接: ${filename}`);
    if ([...body.matchAll(/^# /gm)].length !== 1) throw new Error(`正文只能有一个一级标题: ${filename}`);
    badges.set(data.id, [...new Set([...body.matchAll(/!\[[^\]]*\]\(https:\/\/img\.shields\.io\/(?:github\/(?:stars|license)\/|badge\/license-)[^\s)]+\)/g)].map(match => match[0]))]);
    resources.push({ ...data, path: slash(path.relative(root, filename)) });
  }
  if (!resources.length) throw new Error('资源目录不能为空');
  return { categories, resources, badges };
}

export function outputs(categories, sourceResources, badges = new Map()) {
  const resources = [...sourceResources].sort((a, b) => compare(a.id, b.id));
  const counts = new Map();
  for (const r of resources) counts.set(r.category, (counts.get(r.category) ?? 0) + 1);
  const index = [generated, '# 资源导航\n', '按分类组浏览资源；每项资源的介绍、链接和状态保存在独立文件中。\n', '[返回首页](../readme.md) · [贡献规范](../CONTRIBUTING.md)\n'];
  const pages = new Map(), indexGroups = new Map();
  for (const c of categories) {
    const [group, sub] = c.id.split('/'), count = counts.get(c.id) ?? 0;
    if (!pages.has(group)) {
      pages.set(group, [generated, `# ${c.group}\n`, '按用途分类浏览资源；表格保留资源的 Star 数和开源协议徽章。\n', '[全部资源](../readme.md) · [贡献规范](../../CONTRIBUTING.md)\n']);
      indexGroups.set(group, []);
    }
    indexGroups.get(group).push(`| [${c.title}](${group}/readme.md#${sub}) | ${count} |`);
    const page = pages.get(group);
    page.push(`<a id="${sub}"></a>\n`, `## ${c.title}\n`);
    if (c.description) page.push(`${c.description}\n`);
    page.push('| 资源 | ID | 状态 | Star 数 / 开源协议 |', '| --- | --- | --- | --- |');
    for (const r of resources.filter(r => r.category === c.id)) {
      const title = r.title.replaceAll('|', '\\|').replaceAll('[', '\\[').replaceAll(']', '\\]');
      const status = { unknown: '待确认', active: '维护中', archived: '已停止' }[r.status];
      page.push(`| [${title}](${sub}/${r.id}.md) | \`${r.id}\` | ${status} | ${(badges.get(r.id) ?? []).join(' ')} |`);
    }
    page.push('');
  }
  for (const [group, rows] of indexGroups) {
    const members = categories.filter(c => c.id.split('/')[0] === group);
    const title = members[0].group;
    index.push(`## ${title}\n`, `[浏览${title}](${group}/readme.md)\n`, '| 分类 | 资源数 |', '| --- | --- |', ...rows, '');
  }
  const result = { 'resources/readme.md': `${index.join('\n').trimEnd()}\n` };
  for (const [group, page] of pages) result[`resources/${group}/readme.md`] = `${page.join('\n').trimEnd()}\n`;
  result['resources/index.json'] = `${JSON.stringify(resources, null, 2)}\n`;
  for (const [filename, form] of Object.entries(issueForms(categories))) {
    result[filename] = '# Generated by scripts/check/catalog.js\n' + stringify(form, { lineWidth: 0 });
  }
  return result;
}

export function checkLocalLinks(root = ROOT) {
  const files = ['readme.md', 'CONTRIBUTING.md', 'docs/readme.md'].map(f => path.join(root, f));
  files.push(...markdownFiles(path.join(root, 'maintenance')), ...markdownFiles(path.join(root, 'resources')));
  for (const filename of files) {
    for (const match of read(filename).matchAll(/\]\(<?([^\s)>]+)>?(?:\s+"[^"]*")?\)/g)) {
      const target = match[1];
      if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('#')) continue;
      const urlPath = target.split(/[?#]/, 1)[0];
      if (!urlPath) continue;
      const destination = path.resolve(path.dirname(filename), decodeURIComponent(urlPath));
      const relative = path.relative(fs.realpathSync(root), fs.existsSync(destination) ? fs.realpathSync(destination) : destination);
      if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative) || !fs.existsSync(destination)) {
        throw new Error(`本地链接不存在或越界: ${path.relative(root, filename)} → ${target}`);
      }
    }
  }
}

export function main(args = process.argv.slice(2), root = ROOT) {
  if (args.some(a => a !== '--check')) throw new Error('用法: node scripts/check/catalog.js [--check]');
  const { categories, resources, badges } = loadResources(root), expected = outputs(categories, resources, badges);
  for (const [filename, content] of Object.entries(expected)) {
    const destination = path.join(root, filename);
    if (args.includes('--check')) {
      if (!fs.existsSync(destination) || read(destination) !== content) throw new Error(`导航需要重新生成: ${filename}`);
    } else {
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.writeFileSync(destination, content);
    }
  }
  for (const file of markdownFiles(path.join(root, 'resources'))) {
    const relative = slash(path.relative(root, file));
    if (/^resources\/[^/]+\/readme\.md$/.test(relative) && !Object.hasOwn(expected, relative)) throw new Error(`存在已删除分类的旧导航，请移除: ${relative}`);
  }
  checkLocalLinks(root);
  console.log(`校验通过：${resources.length} 项资源，${categories.length} 个分类；导航一致，本地文件链接有效。`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(`目录校验失败: ${error.message}`); process.exitCode = 1; }
}
